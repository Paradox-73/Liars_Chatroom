"""Writes a self-contained Kaggle script kernel: <kernel>/run.py (the committed lc loader, prompt and answer parsing,
kjudge.py, the id lists and launcher.py in one file) and <kernel>/kernel-metadata.json.

A phase is split,ids_file,first-last,out_name[,min_accuracy]; first-last are 1-based line numbers of ids_file.
Example (from the repository root):
  python kaggle/build.py kaggle/judge14b --owner <kaggle-username> \
    --model Qwen/Qwen3-14B-AWQ@31c69efc29464b6bb0aee1398b5a7b50a99340c3 \
    --phase train,configs/dev200.txt,1-200,dev200_qwen3-14b-awq_kaggle.jsonl,0.85 \
    --phase test,<ids file>,1-1003,test_qwen3-14b-awq_kaggle.jsonl
"""
import argparse
import json
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
LC_ROOT = os.path.join(HERE, "..")  # repository root
LC_FILES = ["lc/__init__.py", "lc/data.py", "lc/llm/__init__.py", "lc/llm/prompt.py", "lc/llm/judge_vllm.py"]
BANNED = re.compile(r"\bAI\b|claude|assistant|agent", re.I)  # words that must not reach Kaggle


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("kernel", help="kernel folder; its name is the kernel slug")
    ap.add_argument("--model", required=True, help="repo@revision on Hugging Face")
    ap.add_argument("--phase", action="append", required=True)
    ap.add_argument("--budget-hours", type=float, default=11.5, help="session time after which no new case is waited for")
    ap.add_argument("--judge-args", default="", help="extra kjudge.py arguments, e.g. '--max-num-seqs 32'")
    ap.add_argument("--owner", default="YOUR_KAGGLE_USERNAME", help="Kaggle username in the kernel id")
    args = ap.parse_args()

    repo, revision = args.model.split("@")
    phases = []
    for spec in args.phase:
        split, ids_file, span, out, *gate = spec.split(",")
        first, last = map(int, span.split("-"))
        ids = read(ids_file).split()[first - 1:last]
        assert len(ids) == last - first + 1 == len(set(ids)), f"{spec}: {len(ids)} ids"
        phases.append([split, ids, out, float(gate[0]) if gate else None])
    commit = subprocess.run(["git", "-C", LC_ROOT, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "-C", LC_ROOT, "status", "--porcelain", "--", *LC_FILES], capture_output=True, text=True).stdout
    assert not dirty, f"uncommitted changes in the embedded lc files:\n{dirty}"
    files = {rel: read(os.path.join(LC_ROOT, rel)) for rel in LC_FILES}
    files["kjudge.py"] = read(os.path.join(HERE, "kjudge.py"))
    cfg = {"model": {"repo": repo, "revision": revision, "name": repo.split("/")[1].lower()},
           "phases": phases, "budget_hours": args.budget_hours, "judge_args": args.judge_args}
    run_py = (f'"""Generated by kaggle/build.py from lc at commit {commit}; do not edit by hand."""\n'
              f"CFG = {cfg!r}\nFILES = {files!r}\n\n{read(os.path.join(HERE, 'launcher.py'))}")
    slug = os.path.basename(os.path.normpath(args.kernel))
    meta = {"id": f"{args.owner}/{slug}", "title": slug, "code_file": "run.py", "language": "python", "kernel_type": "script",
            "is_private": True, "enable_gpu": True, "enable_tpu": False, "enable_internet": True, "machine_shape": "NvidiaTeslaT4",
            "dataset_sources": [], "competition_sources": ["the-liars-chatroom"], "kernel_sources": [], "model_sources": []}
    for text in (run_py, json.dumps(meta)):
        hit = BANNED.search(text)
        assert not hit, f"banned word {hit.group()!r} in the kernel"
    compile(run_py, "run.py", "exec")
    os.makedirs(args.kernel, exist_ok=True)
    with open(os.path.join(args.kernel, "run.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(run_py)
    with open(os.path.join(args.kernel, "kernel-metadata.json"), "w") as f:
        json.dump(meta, f, indent=2)
    print(f"{args.kernel}/run.py: lc {commit}, {repo}@{revision[:8]}, " + ", ".join(f"{p[0]} {len(p[1])} -> {p[2]}" for p in phases))


if __name__ == "__main__":
    main()
